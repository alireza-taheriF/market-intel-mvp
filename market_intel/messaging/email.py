"""Test-email sending over SMTP with two hard safety gates.

1. The recipient must be exactly ALLOWED_TEST_RECIPIENT. The address of the
   prospect is never used, so a real customer can never be emailed by mistake.
2. Nothing is sent unless `approved=True`, i.e. a human reviewed the text and
   pressed the button in the UI.

Every attempt (success or failure) is appended to runs/email_log.jsonl.
"""
from __future__ import annotations

import json
import smtplib
import socket
import ssl
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from email.message import EmailMessage
from pathlib import Path

from market_intel.core.config import ALLOWED_TEST_RECIPIENT, Settings
from market_intel.core.errors import EmailError, NetworkError, RecipientNotAllowedError, ServiceTimeoutError
from market_intel.core.faults import FaultConfig
from market_intel.core.models import SalesMessage


@dataclass
class EmailResult:
    ok: bool
    recipient: str
    subject: str
    company: str
    detail: str
    sent_at: str


def check_recipient(recipient: str) -> str:
    addr = (recipient or "").strip().lower()
    if addr != ALLOWED_TEST_RECIPIENT:
        raise RecipientNotAllowedError(f"recipient '{recipient}' is not allowed")
    return addr


def build_email(settings: Settings, message: SalesMessage, recipient: str) -> EmailMessage:
    em = EmailMessage()
    em["From"] = settings.smtp_from
    em["To"] = recipient
    em["Subject"] = f"[TEST] {message.subject}"
    em.set_content(
        f"--- TEST EMAIL: drafted for prospect '{message.company_name}', delivered only to the "
        f"internal test inbox. Generated by: {message.generated_by}. ---\n\n{message.body}\n"
    )
    return em


def _deliver(settings: Settings, em: EmailMessage) -> None:
    ctx = ssl.create_default_context()
    try:
        if settings.smtp_security == "ssl":
            server = smtplib.SMTP_SSL(settings.smtp_host, settings.smtp_port, timeout=settings.smtp_timeout_s, context=ctx)
        else:
            server = smtplib.SMTP(settings.smtp_host, settings.smtp_port, timeout=settings.smtp_timeout_s)
        with server:
            if settings.smtp_security == "starttls":
                server.starttls(context=ctx)
            if settings.smtp_user:
                server.login(settings.smtp_user, settings.smtp_password)
            server.send_message(em)
    except smtplib.SMTPAuthenticationError as exc:
        raise EmailError("authentication failed (check SMTP_USER / SMTP_PASSWORD; Gmail needs an App Password)") from exc
    except (socket.timeout, TimeoutError) as exc:
        raise ServiceTimeoutError(f"SMTP server did not answer within {settings.smtp_timeout_s:.0f}s",
                                  service="Email (SMTP)") from exc
    except smtplib.SMTPException as exc:  # subclass of OSError, so it must come first
        raise EmailError(f"SMTP error: {exc}") from exc
    except OSError as exc:  # DNS failure, connection refused, network unreachable
        raise NetworkError(f"cannot connect to {settings.smtp_host}:{settings.smtp_port} ({exc})",
                           service="Email (SMTP)") from exc


def _log(settings: Settings, result: EmailResult) -> None:
    try:
        path = Path(settings.runs_dir)
        path.mkdir(parents=True, exist_ok=True)
        with open(path / "email_log.jsonl", "a", encoding="utf-8") as f:
            f.write(json.dumps(asdict(result), ensure_ascii=False) + "\n")
    except OSError:
        pass  # logging must never break sending


def send_test_email(settings: Settings, message: SalesMessage, recipient: str, *, approved: bool,
                    faults: FaultConfig | None = None) -> EmailResult:
    """Send one approved message to the whitelisted test inbox. Never raises."""
    faults = faults or FaultConfig()
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")

    def done(ok: bool, detail: str) -> EmailResult:
        result = EmailResult(ok, recipient, message.subject, message.company_name, detail, now)
        _log(settings, result)
        return result

    try:
        addr = check_recipient(recipient)
        if not approved:
            raise EmailError("not sent: human approval is required before sending")
        if not message.body.strip():
            raise EmailError("not sent: the message body is empty")
        if faults.smtp_failure:
            raise NetworkError(f"Simulated: connection to {settings.smtp_host or 'SMTP server'} refused",
                               service="Email (SMTP)")
        if not settings.smtp_configured:
            raise EmailError("SMTP is not configured (set SMTP_HOST and SMTP_FROM in .env)")
        if settings.smtp_security not in ("starttls", "ssl", "none"):
            raise EmailError(f"invalid SMTP_SECURITY '{settings.smtp_security}' (use starttls, ssl or none)")
        _deliver(settings, build_email(settings, message, addr))
    except (EmailError, NetworkError, ServiceTimeoutError) as exc:
        return done(False, exc.user_message)
    return done(True, f"Sent to {addr} via {settings.smtp_host}:{settings.smtp_port}")
